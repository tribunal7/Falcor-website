<p>Put both samples flat where the floor will go. At midday, look at the outline of a window frame in each surface. In the evening, turn on the fixtures you normally use and stand in the same spot. A polished surface may repeat a row of bright pendants across the floor. A matte surface makes those individual reflections less distinct. For a lobby, repeat the check from the reception desk as well as the entrance.</p>
